"""Install, sync or uninstall agent-home. Python 3.10+, standard library only."""

import argparse
import hashlib
import json
import os
from pathlib import Path
import re
import runpy
import shutil
import subprocess
import sys
import time

REPO = Path(__file__).resolve().parent
ADAPTERS = {"codex": (".codex", "AGENTS.md"), "claude": (".claude", "CLAUDE.md")}


def digest(data):
    return hashlib.sha256(data).hexdigest()


def read(path):
    if path.is_symlink():
        raise ValueError(f"Symbolic links are not supported: {path}")
    return path.read_bytes() if path.exists() else None


def write(path, data):
    path.parent.mkdir(parents=True, exist_ok=True)
    temporary = path.with_name(path.name + ".agent-home-tmp")
    temporary.write_bytes(data)
    temporary.replace(path)


def layers(machine, harness):
    return [REPO / "common", REPO / "harnesses" / harness,
            REPO / "machines" / machine,
            REPO / "machines" / machine / "harnesses" / harness]


def desired(home, machine, harnesses):
    files = {}
    for harness in harnesses:
        directory, name = ADAPTERS[harness]
        root = home / directory
        if harness == "codex" and os.environ.get("CODEX_HOME"):
            root = Path(os.environ["CODEX_HOME"]).expanduser().resolve()
        instructions = ["<!-- Generated by agent-home. Edit the repository sources. -->"]
        skills = {}
        for layer in layers(machine, harness):
            source = layer / "FRAGMENT.md"
            if source.exists():
                instructions.append(f"<!-- {source.relative_to(REPO).as_posix()} -->\n" +
                                    source.read_text(encoding="utf-8-sig").strip())
            for skill in sorted((layer / "skills").glob("*")):
                if not (skill / "SKILL.md").is_file():
                    raise ValueError(f"Missing SKILL.md: {skill}")
                if skill.name.casefold() in skills:
                    raise ValueError(f"Duplicate skill across scopes: {skill.name}")
                skills[skill.name.casefold()] = skill
        files[str(root / name)] = ("\n\n".join(instructions) + "\n").encode()
        for skill in skills.values():
            for source in sorted(skill.rglob("*")):
                if source.is_symlink():
                    raise ValueError(f"Symbolic link in skill: {source}")
                if source.is_file():
                    files[str(root / "skills" / skill.name / source.relative_to(skill))] = source.read_bytes()
    return files


def load_state(home):
    path = home / ".agent-home" / "state.json"
    state = json.loads(path.read_text(encoding="utf-8")) if path.exists() else None
    if state and Path(state["repo"]).resolve() != REPO.resolve():
        raise ValueError(f"Installed from another clone: {state['repo']}")
    return state


def prune_backups(home):
    for path in (home / ".agent-home" / "backups").glob("*"):
        if path.stat().st_mtime <= time.time() - 7 * 24 * 60 * 60:
            path.unlink()


def apply(home, machine, harnesses, confirm=False):
    if not re.fullmatch(r"[a-z0-9][a-z0-9-]*", machine):
        raise ValueError(f"Invalid machine name: {machine}")
    state = load_state(home)
    previous = state["files"] if state else {}
    wanted = desired(home, machine, harnesses)
    current = {}
    # Check every managed file before making any change, including removals.
    for target in sorted(previous.keys() | wanted.keys()):
        path = Path(target)
        if any(parent.is_symlink() for parent in path.parents):
            raise ValueError(f"Path contains a symbolic-link directory: {path}")
        current[target] = read(path)
        old = previous.get(target)
        if old and (current[target] is None or digest(current[target]) != old["sha256"]):
            raise ValueError(f"Local edit detected; copy it to the repository before continuing: {path}")
    if confirm and state:
        print(f"Current installation: {state['machine']}; {', '.join(state['harnesses'])}")
        print(f"Requested installation: {machine}; {', '.join(harnesses)}")
        removed_harnesses = sorted(set(state["harnesses"]) - set(harnesses))
        if removed_harnesses:
            print("Managed instructions and skills for omitted harnesses will be removed: " +
                  ", ".join(removed_harnesses))
        removed = sorted(previous.keys() - wanted.keys())
        created = sum(current[target] is None for target in wanted)
        updated = sum(current[target] is not None and current[target] != data
                      for target, data in wanted.items())
        print(f"Files: {created} to create, {updated} to update, {len(removed)} to remove.")
        if removed:
            print("Managed files to remove:")
            for target in removed:
                print(f"  {target}")
        try:
            answer = input("Reinstall and apply these changes? [y/N] ")
        except EOFError:
            answer = ""
        if answer.strip().casefold() not in {"y", "yes"}:
            print("Installation cancelled; no files changed.")
            return False
    records = {}
    backup_root = home / ".agent-home" / "backups"
    for target in sorted(previous.keys() | wanted.keys()):
        old = previous.get(target)
        if not old and current[target] is not None:
            backup = backup_root / digest(target.encode())
            write(backup, current[target])
            print(f"Backup created: {target} -> {backup} "
                  "(expires after 7 days; removed on uninstall)")
        if target in wanted:
            if current[target] != wanted[target]:
                write(Path(target), wanted[target])
            records[target] = {"sha256": digest(wanted[target])}
        else:
            Path(target).unlink()
    state = {"repo": str(REPO), "machine": machine, "harnesses": harnesses, "files": records}
    write(home / ".agent-home" / "state.json", (json.dumps(state, indent=2) + "\n").encode())
    prune_backups(home)
    print(f"{machine}: {', '.join(harnesses)}; {len(wanted)} managed files")
    return True


def schedule(remove=False):
    if os.name == "nt":
        command = ["powershell.exe", "-NoProfile", "-File", str(REPO / "setup/windows.ps1")]
        command += ["-Remove"] if remove else []
    elif sys.platform == "darwin":
        command = [sys.executable, str(REPO / "setup/macos.py")]
        command += ["remove"] if remove else []
    else:
        command = ["bash", str(REPO / "setup/linux.sh")]
        command += ["remove"] if remove else []
    subprocess.run(command, check=True)


def uninstall(home):
    if not load_state(home):
        return
    schedule(remove=True)
    shutil.rmtree(home / ".agent-home")
    print("Scheduled sync removed; installed files preserved; state and backups deleted.")


def git(*args):
    return subprocess.check_output(["git", "-C", str(REPO), *args], text=True,
                                   encoding="utf-8", timeout=60).strip()


def sync(home):
    state = load_state(home)
    if not state:
        raise ValueError("Run install first.")
    prune_backups(home)
    if git("branch", "--show-current") != "main":
        raise ValueError("Sync requires main. Develop changes in another clone or worktree.")
    if git("status", "--porcelain"):
        raise ValueError("The repository has local changes. Commit and push them before syncing.")
    git("fetch", "origin", "main")
    if git("rev-list", "FETCH_HEAD..HEAD"):
        raise ValueError("There are unpublished commits. Push them before syncing.")
    git("merge", "--ff-only", "FETCH_HEAD")
    # Load the downloaded code before applying the updated files.
    runpy.run_path(str(REPO / "agent_home.py"))["apply"](home, state["machine"], state["harnesses"])


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    commands = parser.add_subparsers(dest="command", required=True)
    install = commands.add_parser("install")
    install.add_argument("machine")
    install.add_argument("harnesses", choices=ADAPTERS, nargs="+")
    commands.add_parser("sync", help="Fetch origin/main and apply the files")
    commands.add_parser("uninstall", help="Remove scheduled sync, state and backups")
    args = parser.parse_args()
    home = Path.home().resolve()
    if args.command == "install":
        if apply(home, args.machine, list(dict.fromkeys(args.harnesses)), confirm=True):
            (REPO / "machines" / args.machine).mkdir(parents=True, exist_ok=True)
            schedule()
    elif args.command == "sync":
        sync(home)
    else:
        uninstall(home)


if __name__ == "__main__":
    try:
        main()
    except (ValueError, OSError, subprocess.SubprocessError) as error:
        sys.exit(str(error))
